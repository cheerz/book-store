package com.example.bookstore.catalog.adapter.outbound.repository

import com.example.bookstore.catalog.domain.Book
import com.example.bookstore.catalog.domain.BookFormat
import com.example.bookstore.catalog.domain.BookKind
import org.springframework.beans.factory.annotation.Autowired
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest
import org.springframework.context.annotation.Import
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertNotNull

@DataJpaTest
@Import(JpaBookRepository::class)
class JpaBookRepositoryTest
    @Autowired
    constructor(
        private val repository: JpaBookRepository,
    ) {
        @Test
        fun `gives a created book the id generated by the database`() {
            val created = repository.create(Book("Dune", BookKind.SF, BookFormat.HARDCOVER, 1_200))

            assertNotNull(created.id)
        }

        @Test
        fun `lists a created book after the existing ones`() {
            val created = repository.create(Book("Dune", BookKind.SF, BookFormat.HARDCOVER, 1_200))

            assertEquals(created, repository.findAll().last())
        }
    }
